import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const require=createRequire(path.join(repo,'package.json'));
const {createProjectRuntime}=require('./server/runtime/index.cjs');
const root=fs.mkdtempSync('/tmp/dsh-audit-runtime-');fs.mkdirSync(path.join(root,'.awf'));
fs.writeFileSync(path.join(root,'.awf/config.json'),JSON.stringify({runtime:{adapter:'dsh'},run:{decision:{enabled:true,mode:'auto'}}}));
fs.writeFileSync(path.join(root,'.awf/state.json'),JSON.stringify({mode:'run',version:'0.2.0',currentState:'CODE',milestones:[],plan:{},tasks:[{id:'T1',status:'active',kind:'dev'},{id:'T2',status:'pending',kind:'dev'}]}));
const handlers=new Set();const prompts=[];
const emit=p=>{for(const h of handlers)h({cwd:root,...p})};
const bridge={connected:()=>true,lastFacts:()=>({sessionExists:true}),noteFacts:()=>{},onEvent:h=>{handlers.add(h);return()=>handlers.delete(h)},request:async(op,args)=>{if(op==='session.prompt'){prompts.push(args.text);queueMicrotask(()=>emit({type:'session.ready'}));}return {delivery:'accepted',ok:true,result:{accepted:true}}}};
const rt=createProjectRuntime({projectRoot:root,adapterDeps:{bridge}});
emit({type:'session.started',sessionId:'execution-current'});
emit({type:'agent.started',agentId:'old-plan-worker',parentSessionId:'plan-old'});
emit({type:'agent.stopped',agentId:'old-plan-worker',parentSessionId:'plan-old',lastAssistantMessage:'RESULT: {"taskId":"T2","status":"done","result":"wrong run"}'});
console.log(JSON.stringify({name:'R6 actual runtime/store',mainSessionId:rt.session.mainSessionId,state:JSON.parse(fs.readFileSync(path.join(root,'.awf/state.json'))).tasks.map(t=>({id:t.id,status:t.status}))}));
rt.session.setBusy();
const waiting=rt.session.waitReady(1000).then(async()=>{rt.session.setBusy();await rt.ctx.host.sendPrompt('NEXT TASK');});
emit({type:'session.ready',lastAssistantMessage:'<AWF_DECISION_REQUIRED>要不要继续？</AWF_DECISION_REQUIRED>'});
await waiting;await new Promise(r=>setTimeout(r,30));
console.log(JSON.stringify({name:'R7 decision race',promptOrder:prompts.map(p=>p==='NEXT TASK'?p:'DECISION INSTRUCTION')}));
rt.reset();fs.rmSync(root,{recursive:true,force:true});
